import argparse
import csv
from pathlib import Path

import matplotlib.pyplot as plt


METRICS = ["rmse", "r2", "nlpd", "ece"]


def _load_summary(path: Path):
    rows = []
    with path.open("r", newline="") as f:
        reader = csv.DictReader(f)
        for r in reader:
            row = {
                "after_task": int(r["after_task"]),
                "solver": r["solver"],
            }
            for m in METRICS:
                row[f"old_mean_{m}"] = float(r[f"old_mean_{m}"])
                row[f"new_mean_{m}"] = float(r[f"new_mean_{m}"])
            rows.append(row)
    return rows


def _build_gap_series(rows):
    by_task_solver = {(r["after_task"], r["solver"]): r for r in rows}
    tasks = sorted({r["after_task"] for r in rows})

    series = {m: {"old": [], "new": []} for m in METRICS}
    for task in tasks:
        ode = by_task_solver[(task, "ode")]
        ana = by_task_solver[(task, "analytic")]
        for m in METRICS:
            series[m]["old"].append(ana[f"old_mean_{m}"] - ode[f"old_mean_{m}"])
            series[m]["new"].append(ana[f"new_mean_{m}"] - ode[f"new_mean_{m}"])
    return tasks, series


def _plot(tasks, series, out_path: Path):
    fig, axes = plt.subplots(2, 2, figsize=(12, 8), sharex=True)
    axes = axes.flatten()

    titles = {
        "rmse": "RMSE gap (analytic - ode)",
        "r2": "R2 gap (analytic - ode)",
        "nlpd": "NLPD gap (analytic - ode)",
        "ece": "ECE gap (analytic - ode)",
    }

    for ax, m in zip(axes, METRICS):
        ax.plot(tasks, series[m]["old"], marker="o", linewidth=2, label="old (different Task1 kernel)")
        ax.plot(tasks, series[m]["new"], marker="s", linewidth=2, label="new (shared Task1 kernel)")
        ax.axhline(0.0, color="gray", linestyle="--", linewidth=1)
        ax.set_title(titles[m])
        ax.set_xticks(tasks)
        ax.set_xlabel("after_task")
        ax.set_ylabel("gap")
        ax.grid(alpha=0.25, linestyle=":")

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2, frameon=False)
    fig.tight_layout(rect=[0, 0, 1, 0.95])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=180)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(
        description="Plot old vs new solver-gap curves from metrics_compare_summary.csv."
    )
    parser.add_argument(
        "--summary_csv",
        type=str,
        default="ohsgp_shared/metrics_compare_summary.csv",
        help="Path to summary csv generated by metrics comparison.",
    )
    parser.add_argument(
        "--out_png",
        type=str,
        default="ohsgp_shared/solver_gap_old_vs_new.png",
        help="Output png path.",
    )
    args = parser.parse_args()

    summary_path = Path(args.summary_csv)
    out_path = Path(args.out_png)

    rows = _load_summary(summary_path)
    tasks, series = _build_gap_series(rows)
    _plot(tasks, series, out_path)
    print(f"Saved figure: {out_path}")


if __name__ == "__main__":
    main()
